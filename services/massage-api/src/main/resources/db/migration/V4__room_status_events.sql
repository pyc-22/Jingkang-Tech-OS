CREATE TABLE room_status_event (
  id UUID PRIMARY KEY,
  tenant_id UUID NOT NULL REFERENCES tenant(id),
  store_id UUID NOT NULL REFERENCES store(id),
  room_id UUID NOT NULL REFERENCES room(id),
  status VARCHAR(20) NOT NULL CHECK (status IN ('IDLE','IN_SERVICE','CLEANING','RESERVED')),
  reason VARCHAR(240),
  source VARCHAR(30) NOT NULL DEFAULT 'FRONTDESK',
  operator_user_id UUID,
  order_id UUID,
  occurred_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX room_status_event_latest_idx ON room_status_event(tenant_id,store_id,room_id,occurred_at DESC);
